const AppLocaleContext = createContext<AppLocaleContextValue | null>(null);

function resolveInitialLocale(): { locale: AppLocale; isExplicit: boolean } {
  if (typeof window === "undefined") return { locale: "en", isExplicit: false };
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored === "zh" || stored === "en") return { locale: stored, isExplicit: true };
  const browserLocale: AppLocale = window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
  return { locale: browserLocale, isExplicit: false };
}

function interpolate(
  template: string,
  params: Record<string, string | number> = {},
): string {
  return Object.entries(params).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function AppLocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<AppLocale>("en");

  useEffect(() => {
    const { locale: initial, isExplicit } = resolveInitialLocale();
    setLocaleState(initial);

    // The geo hint exists for visitors in China whose browser is configured in
    // English. It can only promote to Chinese: its "en" answer means "no signal"
    // rather than a preference, so someone browsing in Chinese from outside
    // China must keep Chinese.
    if (isExplicit || initial === "zh") return;

    fetch("/api/locale")
      .then((r) => r.json())
      .then((data: { locale?: string }) => {
        if (data.locale === "zh") setLocaleState("zh");
      })
      .catch(() => {});
  }, []);

  const value = useMemo<AppLocaleContextValue>(
    () => ({
      locale,
      setLocale: (next) => {
        setLocaleState(next);
        if (typeof window !== "undefined") {
          window.localStorage.setItem(STORAGE_KEY, next);
        }
      },
      t: (key, params) =>
        interpolate(
          translations[locale][key] ?? translations.en[key] ?? key,
          params,
        ),
    }),
    [locale],
  );

  return (
    <AppLocaleContext.Provider value={value}>
      {children}
    </AppLocaleContext.Provider>
  );
}

export function useAppLocale() {
  const context = useContext(AppLocaleContext);
  if (!context) {
    throw new Error("useAppLocale must be used within AppLocaleProvider");
  }
  return context;
}
